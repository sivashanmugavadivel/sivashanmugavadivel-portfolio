/**
 * Accessories, read straight out of `config.json` → `garage.accessories`.
 *
 * The list lives in config so it can be edited without touching a component.
 * Two views share it: the "Accessories & Add-ons" strip on /mygarage (featured
 * items only) and the full storefront at /mygarage/storefront.
 *
 * Item shape:
 *   {
 *     id:       'insta360-x5',            // stable slug, used as the React key
 *     name:     'Insta360 X5',
 *     desc:     '',                       // optional one-liner; hidden when blank
 *     featured: true,                     // optional; surfaces it on /mygarage
 *     imageKey: 'insta 360 x5',           // optional; only when the photos are
 *                                         // filed under a different name
 *     links:    [{ vendor: 'Amazon', url: 'https://…' }]   // first = primary buy button
 *   }
 *
 * Photos are matched by name, not listed here: drop files into
 * public/mygarage/items named "<product name>_1.jpg", "_2", "_3"… and they get
 * picked up. Matching ignores case, spaces and punctuation, so
 * "SADDLE STAY WITH PLATE WITH FOOTREST_1.png" finds "Saddle Stay with Plate
 * with Footrest". The manifest is regenerated by scripts/gen-item-images.mjs,
 * which runs automatically before `npm run dev` and `npm run build`.
 *
 * To add gear: drop an entry into the right category in config.json. To change
 * what shows on the garage page, move the `featured` flags around.
 */

import cfg from './config.json'
import itemImages from './itemImages.json'

const accessories = cfg.garage?.accessories ?? {}

/** Must stay in step with `keyOf` in scripts/gen-item-images.mjs. */
const keyOf = name => String(name).toLowerCase().replace(/[^a-z0-9]/g, '')

const BASE = import.meta.env.BASE_URL

/** Public URLs for a product's photos, in _1.._n order. Empty when it has none. */
function imagesFor(item) {
  const files = itemImages[keyOf(item.imageKey || item.name)] ?? []
  // Names contain spaces, so they have to be encoded to survive as URLs
  return files.map(f => BASE + f.split('/').map(encodeURIComponent).join('/'))
}

/** Every category, in config order, with empty ones dropped. */
export const accessoryCategories = (accessories.categories ?? [])
  .filter(c => c.items?.length)
  .map(c => ({ ...c, items: c.items.map(item => ({ ...item, images: imagesFor(item) })) }))

/** Optional blurb shown above the list. */
export const accessoriesNote = accessories.note ?? ''

/** Flat list of every item, each tagged with the category it came from. */
export const allAccessories = accessoryCategories.flatMap(c =>
  c.items.map(item => ({ ...item, categoryId: c.id, categoryLabel: c.label, categoryIcon: c.icon })),
)

/**
 * The handful shown on the garage page. Falls back to every item when nothing
 * is flagged, so the strip is never empty just because someone forgot to set a
 * flag. Pass null (or nothing) for `max` to lift the cap entirely — a bare
 * `.slice(0, null)` would silently return nothing.
 */
export function featuredAccessories(max = 6) {
  const flagged = allAccessories.filter(a => a.featured)
  const list = flagged.length ? flagged : allAccessories
  return max == null ? list : list.slice(0, max)
}

export const accessoryCount = allAccessories.length
